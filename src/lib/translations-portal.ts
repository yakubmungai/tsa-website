/**
 * Strings for the member portal and the officers' tools: balances, claims,
 * payments and the admin workflow.
 *
 * Swahili is written first and is the source of truth for the shape: the
 * English dictionary must supply every key it has, which the type enforces.
 * Wording is deliberately plain — many members are older and read Swahili
 * first — so there is no "ledger", "assessment" or "allocation" anywhere a
 * member will see it.
 *
 * Kept apart from translations.ts, which holds the public site.
 */

type Widen<T> = T extends string
  ? string
  : T extends (...args: never[]) => unknown
    ? T
    : { [K in keyof T]: Widen<T[K]> };

